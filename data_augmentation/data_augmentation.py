#!/usr/bin/env python
# coding: utf-8
"""
Augments CNN/DailyMail with German translations generated by Llama-3.1-8B-Instruct.
"""

import json

import torch
from datasets import load_from_disk
from torch.utils.data import DataLoader
from tqdm.auto import tqdm
from transformers import AutoModelForCausalLM, AutoTokenizer

SYSTEM_PROMPT = 'You are a Translator. Please translate English to Deutsch.'  # Prompt for the data augmentation
SAVE_EVERY = 5000  # Number of batches between intermediate saves


def data_augment(dataloader, tokenizer, model, device):
    """
    Translates English articles to German with an instruction-tuned LLM.
    Intermediate results are saved every SAVE_EVERY batches and are not included in the return value.

    Args:
        dataloader (DataLoader): DataLoader for the dataset containing English articles.
        tokenizer (Tokenizer): Tokenizer for processing the input text.
        model (PreTrainedModel): Model used to generate the translations.
        device (torch.device): Device the inputs are moved to.
    Returns:
        outputs (list): Remaining dictionaries ('id', 'source', 'label') since the last intermediate save.
    """
    outputs = []
    progress_bar = tqdm(total=len(dataloader), desc='Processing')

    model.eval()
    with torch.inference_mode():
        for j, batch in enumerate(dataloader):
            messages = [[
                {'role': 'system', 'content': SYSTEM_PROMPT},
                {'role': 'user', 'content': article},
            ] for article in batch['article']]
            inputs = tokenizer.apply_chat_template(
                messages, add_generation_prompt=True, padding=True,
                return_tensors='pt', return_dict=True,
            ).to(device)
            generation = model.generate(
                **inputs,
                max_new_tokens=8192,
                num_beams=5,
                early_stopping=True,
                pad_token_id=tokenizer.pad_token_id,
            )
            # Keep only the newly generated tokens (drop the echoed prompt).
            prompt_len = inputs['input_ids'].shape[1]
            output = tokenizer.batch_decode(generation[:, prompt_len:], skip_special_tokens=True)

            for i in range(len(batch['id'])):
                outputs.append({
                    'id': batch['id'][i],
                    'source': batch['article'][i],
                    'label': output[i].strip(),
                })
            progress_bar.update(1)
            progress_bar.set_description(f'input_length: {prompt_len}')

            if j % SAVE_EVERY == 0 and j != 0:
                save_json(outputs, f'./data/augmented_data/train_re_data_{j // SAVE_EVERY}.json')
                outputs = []

    return outputs


def save_json(outputs, save_path):
    """
    Saves the outputs to a JSON file.

    Args:
        outputs (list): The data to be saved.
        save_path (str): The path where the JSON file will be saved.
    """
    with open(save_path, 'wt', encoding='utf-8') as f:
        json.dump(outputs, f, indent=4)
    print(f'data saved as {save_path}')


def main():
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

    # (1) Load the model and tokenizer
    model_id = 'meta-llama/Meta-Llama-3.1-8B-Instruct'

    model = AutoModelForCausalLM.from_pretrained(
        model_id,
        torch_dtype=torch.bfloat16,
        device_map='auto',
        attn_implementation='flash_attention_2',
    )
    tokenizer = AutoTokenizer.from_pretrained(model_id)
    tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = 'left'  # Decoder-only generation requires left padding

    # (2) Load the dataset
    dataset = load_from_disk('./data/cnn_dailymail')

    # (3) Augment the data
    split = 'train'
    print(f'Processing {split} dataset...')
    dataloader = DataLoader(dataset[split], batch_size=1, shuffle=True)
    outputs = data_augment(dataloader, tokenizer, model, device)
    save_json(outputs, f'./data/augmented_data/{split}_data.json')


if __name__ == '__main__':
    main()
